-- 5.1 Ticket ID Generator Trigger
CREATE OR REPLACE FUNCTION public.trg_generate_ticket_id()
RETURNS TRIGGER AS $$
DECLARE
  year_str text;
  seq_str text;
BEGIN
  IF NEW.id IS NULL OR NEW.id = '' THEN
    year_str := to_char(CURRENT_DATE, 'YYYY');
    seq_str := lpad(nextval('ticket_seq')::text, 5, '0');
    NEW.id := 'ARG-' || year_str || '-' || seq_str;
  END IF;
  RETURN NEW;
END;
$$ LANGUAGE plpgsql;

CREATE TRIGGER set_ticket_id
BEFORE INSERT ON public.tickets
FOR EACH ROW
EXECUTE FUNCTION public.trg_generate_ticket_id();

-- 5.2 Ticket Audit Trail Trigger
CREATE OR REPLACE FUNCTION public.trg_audit_ticket_changes()
RETURNS TRIGGER AS $$
DECLARE
  actor_id_val uuid;
BEGIN
  -- Extract actor UUID from transaction request context or fallback to reporter
  BEGIN
    actor_id_val := coalesce(
      nullif(current_setting('request.jwt.claims', true)::json->>'sub', '')::uuid,
      NEW.reporter_id
    );
  EXCEPTION WHEN OTHERS THEN
    actor_id_val := NEW.reporter_id;
  END;

  IF OLD.status IS DISTINCT FROM NEW.status THEN
    INSERT INTO public.ticket_events (ticket_id, actor_id, event_type, old_value, new_value)
    VALUES (NEW.id, actor_id_val, 'status_change', OLD.status::text, NEW.status::text);
  END IF;

  IF OLD.severity IS DISTINCT FROM NEW.severity THEN
    INSERT INTO public.ticket_events (ticket_id, actor_id, event_type, old_value, new_value)
    VALUES (NEW.id, actor_id_val, 'severity_change', OLD.severity::text, NEW.severity::text);
  END IF;

  IF OLD.assigned_owner_id IS DISTINCT FROM NEW.assigned_owner_id THEN
    INSERT INTO public.ticket_events (ticket_id, actor_id, event_type, old_value, new_value)
    VALUES (NEW.id, actor_id_val, 'assignment_change', OLD.assigned_owner_id::text, NEW.assigned_owner_id::text);
  END IF;

  RETURN NEW;
END;
$$ LANGUAGE plpgsql SECURITY DEFINER;

CREATE TRIGGER audit_ticket_changes
AFTER UPDATE ON public.tickets
FOR EACH ROW
EXECUTE FUNCTION public.trg_audit_ticket_changes();

-- 5.3 Updated At Auto-Maintenance Trigger
CREATE OR REPLACE FUNCTION public.trg_update_updated_at()
RETURNS TRIGGER AS $$
BEGIN
  NEW.updated_at := timezone('utc'::text, now());
  RETURN NEW;
END;
$$ LANGUAGE plpgsql;

CREATE TRIGGER update_plants_updated_at BEFORE UPDATE ON public.plants FOR EACH ROW EXECUTE FUNCTION public.trg_update_updated_at();
