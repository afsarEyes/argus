-- 8. Database Webhooks for Edge Functions
-- =========================================================================

-- Enable pg_net extension to support asynchronous HTTP POST webhook triggers
CREATE EXTENSION IF NOT EXISTS pg_net WITH SCHEMA extensions;

-- Handler function to forward ticket creation events to the auto-assign Edge Function
CREATE OR REPLACE FUNCTION public.trg_webhook_auto_assign()
RETURNS trigger AS $$
BEGIN
  PERFORM
    net.http_post(
      url := coalesce(
        nullif(current_setting('custom.supabase_url', true), ''),
        'http://localhost:54321'
      ) || '/functions/v1/auto-assign-ticket',
      headers := jsonb_build_object(
        'Content-Type', 'application/json',
        'Authorization', 'Bearer ' || coalesce(nullif(current_setting('custom.service_role_key', true), ''), 'service-key')
      ),
      body := jsonb_build_object(
        'type', TG_OP,
        'table', TG_TABLE_NAME,
        'schema', TG_TABLE_SCHEMA,
        'record', row_to_json(NEW)
      )
    );
  RETURN NEW;
END;
$$ LANGUAGE plpgsql SECURITY DEFINER;

-- Bind webhook trigger to tickets table after insert events
CREATE OR REPLACE TRIGGER on_ticket_created
  AFTER INSERT ON public.tickets
  FOR EACH ROW
  EXECUTE FUNCTION public.trg_webhook_auto_assign();

