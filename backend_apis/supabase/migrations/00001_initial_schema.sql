-- Safe role resolver to prevent circular dependencies in RLS policies
CREATE OR REPLACE FUNCTION public.get_my_role()
RETURNS user_role SECURITY DEFINER AS $$
DECLARE
  my_role user_role;
BEGIN
  SELECT role INTO my_role FROM public.users WHERE id = auth.uid();
  RETURN coalesce(my_role, 'staff'::user_role);
END;
$$ LANGUAGE plpgsql;

