-- 00001_initial_schema.sql
-- Initial database schema for Argus (Bundle ID: com.signode.argus)

-- =========================================================================
-- 1. Custom Enum Types
-- =========================================================================

CREATE TYPE user_role AS ENUM ('staff', 'line_owner', 'supervisor', 'quality_manager', 'admin');
CREATE TYPE ticket_status AS ENUM ('open', 'assigned', 'in_progress', 'resolved', 'closed');
CREATE TYPE ticket_severity AS ENUM ('critical', 'major', 'minor');

-- =========================================================================
-- 2. Sequences
-- =========================================================================

-- Sequence for autoincrementing human-readable ticket IDs
CREATE SEQUENCE ticket_seq START 1;

-- =========================================================================
-- 3. Core Database Tables
-- =========================================================================

-- 3.1 Plants
CREATE TABLE public.plants (
  id uuid PRIMARY KEY DEFAULT gen_random_uuid(),
  name text NOT NULL,
  location text,
  active boolean NOT NULL DEFAULT true,
  created_at timestamp with time zone DEFAULT timezone('utc'::text, now()) NOT NULL,
  updated_at timestamp with time zone DEFAULT timezone('utc'::text, now()) NOT NULL
);

-- 3.2 Lines
CREATE TABLE public.lines (
  id uuid PRIMARY KEY DEFAULT gen_random_uuid(),
  plant_id uuid NOT NULL REFERENCES public.plants(id) ON DELETE CASCADE,
  name text NOT NULL,
  active boolean NOT NULL DEFAULT true,
  created_at timestamp with time zone DEFAULT timezone('utc'::text, now()) NOT NULL,
  updated_at timestamp with time zone DEFAULT timezone('utc'::text, now()) NOT NULL
);

-- 3.3 Stations
CREATE TABLE public.stations (
  id uuid PRIMARY KEY DEFAULT gen_random_uuid(),
  line_id uuid NOT NULL REFERENCES public.lines(id) ON DELETE CASCADE,
  name text NOT NULL,
  active boolean NOT NULL DEFAULT true,
  created_at timestamp with time zone DEFAULT timezone('utc'::text, now()) NOT NULL,
  updated_at timestamp with time zone DEFAULT timezone('utc'::text, now()) NOT NULL
);

-- 3.4 Defect Categories
CREATE TABLE public.defect_categories (
  id uuid PRIMARY KEY DEFAULT gen_random_uuid(),
  name text NOT NULL,
  description text,
  active boolean NOT NULL DEFAULT true,
  created_at timestamp with time zone DEFAULT timezone('utc'::text, now()) NOT NULL,
  updated_at timestamp with time zone DEFAULT timezone('utc'::text, now()) NOT NULL
);

-- 3.5 Users (Synchronized profile extension of auth.users)
CREATE TABLE public.users (
  id uuid PRIMARY KEY REFERENCES auth.users(id) ON DELETE CASCADE,
  email text NOT NULL,
  name text NOT NULL,
  role user_role NOT NULL DEFAULT 'staff',
  plant_id uuid REFERENCES public.plants(id) ON DELETE SET NULL,
  line_id uuid REFERENCES public.lines(id) ON DELETE SET NULL,
  shift text,
  avatar_url text,
  is_active boolean NOT NULL DEFAULT true,
  created_at timestamp with time zone DEFAULT timezone('utc'::text, now()) NOT NULL,
  updated_at timestamp with time zone DEFAULT timezone('utc'::text, now()) NOT NULL
);

-- 3.6 Tickets
CREATE TABLE public.tickets (
  id text PRIMARY KEY, -- Formatted like ARG-2026-00042 (Generated by Trigger)
  reporter_id uuid NOT NULL REFERENCES public.users(id) ON DELETE RESTRICT,
  line_id uuid NOT NULL REFERENCES public.lines(id) ON DELETE RESTRICT,
  station_id uuid NOT NULL REFERENCES public.stations(id) ON DELETE RESTRICT,
  defect_category_id uuid NOT NULL REFERENCES public.defect_categories(id) ON DELETE RESTRICT,
  severity ticket_severity NOT NULL,
  photos text[] NOT NULL DEFAULT '{}',
  voice_note_url text,
  description text NOT NULL,
  status ticket_status NOT NULL DEFAULT 'open',
  assigned_owner_id uuid REFERENCES public.users(id) ON DELETE SET NULL,
  offline_id uuid UNIQUE,
  created_at timestamp with time zone DEFAULT timezone('utc'::text, now()) NOT NULL,
  updated_at timestamp with time zone DEFAULT timezone('utc'::text, now()) NOT NULL,
  acknowledged_at timestamp with time zone,
  resolved_at timestamp with time zone,
  closed_at timestamp with time zone,
  root_cause text,
  corrective_action text
);

-- 3.7 Ticket Events (Audit Trail Logs)
CREATE TABLE public.ticket_events (
  id uuid PRIMARY KEY DEFAULT gen_random_uuid(),
  ticket_id text NOT NULL REFERENCES public.tickets(id) ON DELETE CASCADE,
  actor_id uuid NOT NULL REFERENCES public.users(id) ON DELETE RESTRICT,
  event_type text NOT NULL,
  old_value text,
  new_value text,
  created_at timestamp with time zone DEFAULT timezone('utc'::text, now()) NOT NULL
);

-- 3.8 Assignment Rules
CREATE TABLE public.assignment_rules (
  id uuid PRIMARY KEY DEFAULT gen_random_uuid(),
  line_id uuid NOT NULL REFERENCES public.lines(id) ON DELETE CASCADE,
  defect_category_id uuid NOT NULL REFERENCES public.defect_categories(id) ON DELETE CASCADE,
  shift text,
  assigned_owner_id uuid NOT NULL REFERENCES public.users(id) ON DELETE CASCADE,
  created_at timestamp with time zone DEFAULT timezone('utc'::text, now()) NOT NULL,
  updated_at timestamp with time zone DEFAULT timezone('utc'::text, now()) NOT NULL
);

-- 3.9 SLA Targets
CREATE TABLE public.sla_targets (
  id uuid PRIMARY KEY DEFAULT gen_random_uuid(),
  severity ticket_severity NOT NULL UNIQUE,
  target_minutes integer NOT NULL,
  created_at timestamp with time zone DEFAULT timezone('utc'::text, now()) NOT NULL,
  updated_at timestamp with time zone DEFAULT timezone('utc'::text, now()) NOT NULL
);

-- 3.10 Notification Logs
CREATE TABLE public.notifications_log (
  id uuid PRIMARY KEY DEFAULT gen_random_uuid(),
  user_id uuid NOT NULL REFERENCES public.users(id) ON DELETE CASCADE,
  ticket_id text REFERENCES public.tickets(id) ON DELETE SET NULL,
  title text NOT NULL,
  body text NOT NULL,
  sent_at timestamp with time zone DEFAULT timezone('utc'::text, now()) NOT NULL
);

