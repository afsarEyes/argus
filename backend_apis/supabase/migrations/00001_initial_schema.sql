-- Staff read tickets on their line and create tickets
CREATE POLICY select_staff ON public.tickets FOR SELECT TO authenticated USING (
  get_my_role() = 'staff' AND line_id = (SELECT line_id FROM public.users WHERE id = auth.uid())
);
CREATE POLICY insert_staff ON public.tickets FOR INSERT TO authenticated WITH CHECK (
  get_my_role() = 'staff' AND reporter_id = auth.uid()
);

-- Department Leads (Line Owners, Supervisors) read and update tickets on their line, assigned to them, or matching assignment rules
CREATE POLICY select_leads ON public.tickets FOR SELECT TO authenticated USING (
  get_my_role() IN ('line_owner', 'supervisor') AND (
    line_id = (SELECT line_id FROM public.users WHERE id = auth.uid()) OR
    assigned_owner_id = auth.uid() OR
    EXISTS (
      SELECT 1 FROM public.assignment_rules
      WHERE assignment_rules.assigned_owner_id = auth.uid()
        AND assignment_rules.line_id = tickets.line_id
        AND assignment_rules.defect_category_id = tickets.defect_category_id
    )
  )
);
CREATE POLICY update_leads ON public.tickets FOR UPDATE TO authenticated USING (
  get_my_role() IN ('line_owner', 'supervisor') AND (
    line_id = (SELECT line_id FROM public.users WHERE id = auth.uid()) OR
    assigned_owner_id = auth.uid() OR
    EXISTS (
      SELECT 1 FROM public.assignment_rules
      WHERE assignment_rules.assigned_owner_id = auth.uid()
        AND assignment_rules.line_id = tickets.line_id
        AND assignment_rules.defect_category_id = tickets.defect_category_id
    )
  )
) WITH CHECK (
  get_my_role() IN ('line_owner', 'supervisor')
);

-- 7.4 Ticket Events (Selectable if user can select parent ticket)
