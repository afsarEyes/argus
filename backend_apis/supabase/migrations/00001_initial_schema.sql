CREATE TRIGGER update_stations_updated_at BEFORE UPDATE ON public.stations FOR EACH ROW EXECUTE FUNCTION public.trg_update_updated_at();
CREATE TRIGGER update_defect_categories_updated_at BEFORE UPDATE ON public.defect_categories FOR EACH ROW EXECUTE FUNCTION public.trg_update_updated_at();
CREATE TRIGGER update_users_updated_at BEFORE UPDATE ON public.users FOR EACH ROW EXECUTE FUNCTION public.trg_update_updated_at();
CREATE TRIGGER update_tickets_updated_at BEFORE UPDATE ON public.tickets FOR EACH ROW EXECUTE FUNCTION public.trg_update_updated_at();
CREATE TRIGGER update_assignment_rules_updated_at BEFORE UPDATE ON public.assignment_rules FOR EACH ROW EXECUTE FUNCTION public.trg_update_updated_at();
